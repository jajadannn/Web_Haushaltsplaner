# Summe der Split-Zeilen = Buchungsbetrag; zusätzlich zur Prüfung im Service.
# Als DEFERRABLE-Constraint-Trigger, damit Zeilen und Betrag in einer Transaktion
# nacheinander geändert werden können – geprüft wird beim COMMIT.
SPLIT_SUM_FUNCTION = """
CREATE FUNCTION check_split_sum() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    tid integer;
    tx_amount numeric;
    split_sum numeric;
    split_count integer;
BEGIN
    IF TG_TABLE_NAME = 'transaction' THEN
        tid := NEW.id;
    ELSIF TG_OP = 'DELETE' THEN
        tid := OLD.transaction_id;
    ELSE
        tid := NEW.transaction_id;
    END IF;

    SELECT amount INTO tx_amount FROM "transaction" WHERE id = tid;
    IF NOT FOUND THEN
        RETURN NULL;  -- Buchung samt Zeilen gelöscht
    END IF;

    SELECT count(*), coalesce(sum(amount), 0) INTO split_count, split_sum
    FROM transaction_split WHERE transaction_id = tid;

    IF split_count > 0 AND split_sum <> tx_amount THEN
        RAISE EXCEPTION 'Summe der Split-Zeilen (%) ungleich Buchungsbetrag (%) bei Buchung %',
            split_sum, tx_amount, tid
            USING ERRCODE = 'check_violation', CONSTRAINT = 'split_sum_matches_amount';
    END IF;
    RETURN NULL;
END
$$;
"""


