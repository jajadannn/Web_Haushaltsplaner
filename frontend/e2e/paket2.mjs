// Durchklick Paket 2 (Kredite, Fixkosten) gegen die Demo-API: node e2e/paket2.mjs
import { chromium } from 'playwright'

const BASE = process.env.BASE ?? 'http://localhost:5173'
const OUT = process.env.OUT ?? '../.impeccable/review'
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, timezoneId: 'Europe/Berlin' })
await page.addInitScript(() => localStorage.setItem('finanzplaner.profile', JSON.stringify({ id: 1, name: 'Fabian' })))
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
page.on('response', (r) => r.status() === 404 && errors.push('404 ' + r.url()))
const step = (msg) => console.log('•', msg)
const cents = (text) => {
  const m = /(−|-)?([\d.]+),(\d\d)/.exec(text)
  return (m[1] ? -1 : 1) * (Number(m[2].replace(/\./g, '')) * 100 + Number(m[3]))
}

// --- Kredit: Rate 2 buchen, Restschuld sinkt um den Tilgungsanteil, dann stornieren
await page.goto(BASE + '/kredite')
const card = page.locator('.loan-card', { hasText: 'Autokredit' })
const debtText = (await card.locator('.loan-card-debt').textContent()).trim()
const debtBefore = cents(debtText)
const row2 = page.locator('.plan tbody tr', { has: page.locator('td:first-child', { hasText: /^2$/ }) })
const principal2 = cents(await row2.locator('td').nth(4).textContent())
await page.getByRole('button', { name: 'Rate buchen' }).click()
const dialog = page.getByRole('dialog')
await dialog.getByText(/Rate 2, fällig am/).waitFor()
await page.screenshot({ path: `${OUT}/e2e-rate-dialog.png` })
await dialog.getByRole('button', { name: 'Rate buchen' }).click()
await page.getByText('Rate 2 gebucht').waitFor()
await page.waitForFunction((b) => !document.querySelector('.loan-card .loan-card-debt')?.textContent?.includes(b), debtText)
const debtAfter = cents(await card.locator('.loan-card-debt').textContent())
if (debtBefore - debtAfter !== principal2) throw new Error(`Restschuld sank um ${(debtBefore - debtAfter) / 100}, erwartet ${principal2 / 100}`)
step(`Rate 2 gebucht – Restschuld sinkt genau um den Tilgungsanteil ${principal2 / 100}`)
await row2.getByText('bezahlt').waitFor()

await row2.getByRole('button', { name: 'stornieren' }).click()
await page.getByRole('dialog').getByRole('button', { name: 'Stornieren' }).click()
await page.getByText('Rate storniert').waitFor()
await page.waitForFunction((b) => document.querySelector('.loan-card .loan-card-debt')?.textContent?.trim() === b, debtText)
if (cents(await card.locator('.loan-card-debt').textContent()) !== debtBefore) throw new Error('Storno stellt die Restschuld nicht wieder her')
step('Storno stellt Restschuld und Plan wieder her')

// --- Rate aussetzen und zurücknehmen
await row2.getByRole('button', { name: 'aussetzen' }).click()
await page.getByRole('dialog').getByRole('button', { name: 'Aussetzen' }).click()
await page.getByText('Rate ausgesetzt').waitFor()
await row2.getByText('ausgesetzt').waitFor()
await row2.getByRole('button', { name: 'zurücknehmen' }).click()
await page.getByRole('dialog').getByRole('button', { name: 'Zurücknehmen' }).click()
await page.getByText('Aussetzen zurückgenommen').waitFor()
step('Rate ausgesetzt und wieder eingeplant')

// --- Neuer Privatkredit 0 %, dann löschen
await page.getByRole('button', { name: 'Kredit anlegen' }).click()
const form = page.getByRole('dialog')
await form.getByRole('radio', { name: 'Privatkredit' }).click()
await form.getByLabel('Name', { exact: true }).fill('E2E Privatkredit')
await form.getByLabel('Kreditgeber', { exact: true }).fill('Oma')
await form.getByLabel('Zinssatz (% pro Jahr)').fill('0')
await form.getByLabel('Restschuld heute').fill('1.200')
await form.getByLabel('Vereinbarte Rate (optional)').fill('100')
await form.getByLabel('Rate wird gezahlt vom').selectOption({ label: 'Girokonto' })
await form.getByRole('button', { name: 'Anlegen' }).click()
await page.getByText('Kredit angelegt').waitFor()
await page.locator('.loan-card', { hasText: 'E2E Privatkredit' }).locator('.loan-card-debt', { hasText: '1.200,00' }).waitFor()
step('Privatkredit 1.200 € angelegt und ausgewählt')
await page.getByRole('button', { name: 'Konditionen ändern' }).click()
await page.getByRole('dialog').getByRole('button', { name: 'Kredit löschen' }).click()
await page.getByRole('dialog', { name: 'Kredit löschen?' }).getByRole('button', { name: 'Löschen' }).click()
await page.getByText('Kredit gelöscht').waitFor()
await page.locator('.loan-card', { hasText: 'E2E Privatkredit' }).waitFor({ state: 'detached' })
step('Privatkredit wieder gelöscht')

// --- Fixkosten: anlegen → erscheint auf der Startseite → pausieren → löschen
await page.goto(BASE + '/einstellungen/fixkosten')
await page.getByRole('button', { name: 'Fixkost anlegen' }).first().click()
const fx = page.locator('.settings-form')
await fx.getByLabel('Name', { exact: true }).fill('E2E Versicherung')
await fx.getByLabel('Betrag', { exact: true }).fill('45,10')
await fx.getByLabel('Fälligkeitstag').selectOption('28')
await fx.getByRole('button', { name: 'Anlegen' }).click()
await page.getByText('Fixkost angelegt').waitFor()
await page.goto(BASE + '/')
await page.locator('.row-card', { hasText: 'E2E Versicherung' }).waitFor()
step('neue Fixkost erscheint auf der Startseite')
await page.goto(BASE + '/einstellungen/fixkosten')
const fxRow = page.locator('.settings-row', { hasText: 'E2E Versicherung' })
await fxRow.getByRole('switch').click()
await fxRow.getByText('pausiert').waitFor()
await fxRow.click()
await page.locator('.settings-form').getByRole('button', { name: 'Löschen' }).click()
await page.getByRole('dialog').getByRole('button', { name: 'Löschen' }).click()
await page.getByText('Fixkost gelöscht').waitFor()
step('Fixkost pausiert und gelöscht')

if (errors.length) throw new Error('Konsolenfehler:\n' + errors.join('\n'))
console.log('OK – Paket-2-Durchklick bestanden')
await browser.close()
